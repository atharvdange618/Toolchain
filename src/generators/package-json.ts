import type { ProjectInfo } from '../detectors/project.js';
import type { Entry, PlanMessage } from './entry.js';

const SCRIPTS: Record<string, string> = {
  commit: 'cz',
  format: 'prettier --write .',
  'format:check': 'prettier --check .',
  lint: 'oxlint .',
  'lint:fix': 'oxlint . --fix',
  'lint:strict': 'oxlint . --deny-warnings',
  prepare: 'husky',
  typecheck: 'tsc --noEmit',
};

// oxlint --fix applies fixes for warn-level rules as well as errors, and a fix
// can leave code the next run rejects: merging duplicate imports can orphan a
// binding that eslint/no-unused-vars then flags, and that rule has no fixer.
// The plain run right after reports it in the same hook, instead of leaving
// typecheck to fail on it with a less obvious message.
// Expo keeps plain .js sources and config plugins, which the .ts glob would
// skip entirely.
// The glob matches files .oxlintrc.json ignores (*.config.*, components/ui),
// and oxlint exits 1 when every file it gets is ignored, so a commit staging
// only those would fail. The flag stops that; real lint errors still fail.
function lintStaged(info: ProjectInfo): Record<string, string[]> {
  const code = info.framework === 'expo' ? '*.{js,jsx,cjs,mjs,ts,tsx}' : '*.{ts,tsx}';
  const unmatched = '--no-error-on-unmatched-pattern';
  return {
    '*.{json,md,css}': ['prettier --write'],
    [code]: [`oxlint --fix ${unmatched}`, `oxlint ${unmatched}`, 'prettier --write'],
  };
}

// cz-commitlint reads the commitlint.config.mjs already generated by this
// tool to drive its interactive prompt, so there's no second source of
// truth to keep in sync.
const COMMITIZEN_CONFIG = { path: '@commitlint/cz-commitlint' };

// Reads the parsed package.json and writes nothing: the entries say what each
// key should become, and applyEntries keeps existing keys where they are.
export function planPackageJson(
  pkg: Record<string, unknown>,
  info: ProjectInfo,
  toolchainDeps: Record<string, string>,
): { entries: Entry[]; messages: PlanMessage[] } {
  const entries: Entry[] = [];
  const messages: PlanMessage[] = [];
  const warn = (text: string): void => {
    messages.push({ level: 'warn', text });
  };

  // -b follows project references. No --noEmit: a project another one
  // references must emit (TS6310), and solution configs like create-vite's
  // already set noEmit per project.
  let scripts = info.hasProjectReferences ? { ...SCRIPTS, typecheck: 'tsc -b' } : SCRIPTS;

  // Next 15.5+ declares RouteContext, LayoutProps and PageProps in files that
  // only `next typegen` (or a dev or build run) writes. On a fresh checkout or
  // in CI, tsc fails with TS2304 and type-aware oxlint reads them as
  // error-typed values, so every script that runs either gets typegen first.
  const deps = {
    ...(pkg['devDependencies'] as Record<string, string>),
    ...(pkg['dependencies'] as Record<string, string>),
  };
  if (info.framework === 'next' && hasNextTypegen(deps['next'])) {
    const typed = ['typecheck', 'lint', 'lint:fix', 'lint:strict'];
    scripts = Object.fromEntries(
      Object.entries(scripts).map(([key, cmd]) => [
        key,
        typed.includes(key) ? `next typegen && ${cmd}` : cmd,
      ]),
    );
  }

  const existingScripts = (pkg['scripts'] as Record<string, string>) ?? {};

  // init writes no root tsconfig for a monorepo without one (each package
  // has its own), so a root tsc would check every file with the wrong
  // options. The repo's own typecheck (often turbo run check) stays.
  if (info.isMonorepo && !info.hasRootTsconfig) {
    scripts = Object.fromEntries(Object.entries(scripts).filter(([key]) => key !== 'typecheck'));
    if (!('typecheck' in existingScripts)) {
      warn(
        'No typecheck script and no root tsconfig.json, so the pre-commit hook skips typecheck. Add a typecheck script (for example "turbo run check") to turn it on.',
      );
    }
  }
  const conflicts = Object.keys(scripts).filter((key) => key in existingScripts);
  if (conflicts.length > 0) {
    warn(`Overwriting existing scripts: ${conflicts.join(', ')}`);
  }

  for (const [name, cmd] of Object.entries(scripts)) {
    entries.push({ path: `package.json#scripts.${name}`, want: JSON.stringify(cmd) });
  }
  entries.push(
    { path: 'package.json#lint-staged', want: JSON.stringify(lintStaged(info)) },
    { path: 'package.json#config.commitizen', want: JSON.stringify(COMMITIZEN_CONFIG) },
  );

  const allDeps = (pkg['devDependencies'] as Record<string, string>) ?? {};
  const removed = Object.keys(allDeps).filter((name) => ESLINT_DEP.test(name));
  if (removed.length > 0) {
    warn(`Removing ESLint devDependencies (oxlint replaces them): ${removed.join(', ')}`);
  }
  for (const name of removed)
    entries.push({ path: `package.json#devDependencies.${name}`, want: null });
  const existingDeps = Object.fromEntries(
    Object.entries(allDeps).filter(([name]) => !removed.includes(name)),
  );

  const typescriptWarning = typescriptMajorBumpWarning(existingDeps['typescript']);
  if (typescriptWarning) warn(typescriptWarning);
  const depConflicts = Object.keys(toolchainDeps).filter(
    (key) => key in existingDeps && existingDeps[key] !== toolchainDeps[key],
  );
  if (depConflicts.length > 0) {
    warn(
      `Overwriting existing devDependency versions: ${depConflicts
        .map((key) => `${key} (${existingDeps[key]} -> ${toolchainDeps[key]})`)
        .join(', ')}`,
    );
  }
  for (const [name, version] of Object.entries(toolchainDeps)) {
    entries.push({ path: `package.json#devDependencies.${name}`, want: JSON.stringify(version) });
  }

  return { entries, messages };
}

// `next typegen` arrived in Next 15.5. A range's first version decides; a tag
// like latest or canary has none and means a current Next.
export function hasNextTypegen(range: string | undefined): boolean {
  const match = range?.match(/(\d+)(?:\.(\d+))?/);
  if (!match) return true;
  const major = Number(match[1]);
  const minor = Number(match[2] ?? 0);
  return major > 15 || (major === 15 && minor >= 5);
}

// v2 lints with oxlint and moves ESLint configs aside, so these packages
// (v1's own, plus what create-next-app and create-vite add) only cost
// install time. Covers eslint, @eslint/*, typescript-eslint,
// @typescript-eslint/*, eslint-{plugin,config,import-resolver}-* and
// scoped plugins like @next/eslint-plugin-next.
export const ESLINT_DEP =
  /^(eslint|typescript-eslint|@(typescript-)?eslint\/.+|eslint-(plugin|config|import-resolver)-.+|@[^/]+\/eslint-(plugin|config)(-.+)?)$/;

// ponytail: reads the first number in the range, so "~6.0.3" and "^5.8.0"
// count as below 7 and "latest" or "catalog:" are skipped. Use semver's
// minVersion if odd ranges ever show up.
function typescriptMajorBumpWarning(range: string | undefined): string | undefined {
  const major = Number(/\d+/.exec(range ?? '')?.[0]);
  if (Number.isNaN(major) || major >= 7) return undefined;
  return `Upgrading typescript from ${range} to 7. TypeScript 7 drops baseUrl, moduleResolution "node"/"node10", target "es5", outFile, and module "amd"/"umd"/"system". If typecheck fails, remove those from tsconfig.json.`;
}
